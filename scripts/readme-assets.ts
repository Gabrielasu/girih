/**
 * Generates the artwork used in README.md from the real pattern engine.
 * Run with: npx tsx scripts/readme-assets.ts
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import {
  build,
  DEFAULT_RECIPE,
  normalizeRecipe,
  type PatternTile,
  type Recipe,
} from '../src/engine';

const OUT = 'docs/readme';
mkdirSync(OUT, { recursive: true });
const INK = '#121212';
const BLUE = '#2135F5';
const PAPER = '#FBFBFA';
const f = (n: number) => +n.toFixed(3);

function patternDef(id: string, t: PatternTile, sw?: number): string {
  const shapes = t.shapes
    .map(
      (s) =>
        `<path d="${s.d}" transform="${s.transform}" fill="${s.fill}" stroke="${s.stroke}" stroke-width="${sw ?? s.strokeWidth}" vector-effect="non-scaling-stroke"/>`,
    )
    .join('');
  const rot = t.rotation ? ` patternTransform="rotate(${f(t.rotation)})"` : '';
  return `<pattern id="${id}" width="${f(t.width)}" height="${f(t.height)}" patternUnits="userSpaceOnUse"${rot}><rect width="${f(t.width)}" height="${f(t.height)}" fill="${t.background}"/>${shapes}</pattern>`;
}
const r = (p: Partial<Recipe>): Recipe => normalizeRecipe({ ...DEFAULT_RECIPE, ...p });

